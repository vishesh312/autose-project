#!/usr/bin/env bash
# Pull, regenerate docs/results_vllm_qwen.md from results/ (git-ignored) and push it. Run in a loop: see tmux session `pub`.
set -uo pipefail
cd "$(dirname "$0")/.."
export PARBENCH_HOST_POOLS=${PARBENCH_HOST_POOLS:-/scratch/manas/parbench/pools}
PB=/home/manasm/ase/.venv-parbench/bin/parbench
out=docs/results_vllm_qwen.md
{
  echo "# Results: OpenCode + Qwen2.5-7B-Instruct (vLLM, 1x RTX 5000 Ada, no Docker)"
  echo; echo "Auto-generated by scripts/publish_results.sh on $(date -Is). Partial until all runs finish. Python pools of CooperBench \`core\`, k=2, 1 repeat."
  for e in core_opencode_vllm core_opencode_vllm_sm; do
    [ -d results/$e ] || continue
    $PB report results/$e >/dev/null 2>&1
    echo; echo "## $e"; echo; cat results/$e/summary.md 2>/dev/null
    echo; echo "Per run (strategy, pool, wall_s, grade_s, task pass rate, tokens, nudges):"; echo; echo '```'
    python3 - results/$e <<'PY'
import json,glob,os,sys
for f in sorted(glob.glob(sys.argv[1]+"/*/run.json")):
    r=json.load(open(f)); n=os.path.basename(os.path.dirname(f)).split("__"); t=r["time"]; c=r["correctness"]; p=c["by_final"][c["primary"]]; u=r["cost"]["usage"]
    print(n[0], n[3][:34], round(t["wall_clock_s"]), round(t["grading_s"]), p["task_pass_rate"], u["input"]+u["output"], t["nudges"])
PY
    echo '```'
  done
} > $out
git pull -q --rebase --autostash 2>&1 | tail -1
git add $out scripts/publish_results.sh
# raw results too, unless a secret-looking string or one of this shell's secret values is in them
R="results/core_opencode_vllm results/core_opencode_vllm_sm"
env | grep -iE "key|token|secret|passw" | cut -d= -f2- | awk 'length>=8' > "${TMPDIR:-/tmp}/.pub_vals" || true
if { [ -s "${TMPDIR:-/tmp}/.pub_vals" ] && grep -rqFf "${TMPDIR:-/tmp}/.pub_vals" $R 2>/dev/null; } \
   || grep -rIqE "(sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|hf_[A-Za-z0-9]{20,}|AIza[0-9A-Za-z_-]{30,}|AKIA[0-9A-Z]{16})" $R 2>/dev/null; then
  echo "secret-like string found in results; NOT adding raw results"
else
  git add $R
fi
rm -f "${TMPDIR:-/tmp}/.pub_vals"
git commit -q -m "Update vLLM Qwen2.5-7B partial results summary" 2>/dev/null && git push -q 2>&1 | tail -1
